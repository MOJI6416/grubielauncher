export function legacyBiomeId(value: unknown): number | null {
  if (typeof value !== "number" || !Number.isInteger(value)) return null;
  return value < 0 ? value & 0xff : value;
}

export function legacyBiomeName(id: number): string | null {
  const name = LEGACY_BIOMES[id];
  return name ? `minecraft:${name}` : null;
}

export function byteArray(value: unknown): ArrayLike<number> | null {
  if (Array.isArray(value)) return value;
  if (ArrayBuffer.isView(value) && !(value instanceof DataView)) {
    return value as unknown as ArrayLike<number>;
  }
  return null;
}

export function nibble(array: ArrayLike<number>, index: number): number {
  const value = array[index >> 1] ?? 0;
  return (index & 1) === 0 ? value & 0x0f : (value >> 4) & 0x0f;
}
