export type LegacyBlockNames = ReadonlyMap<number, string>;

export function legacyBlockName(
  id: number,
  data: number,
  registry?: LegacyBlockNames | null,
): string {
  const entry = LEGACY_BLOCKS[id];

  if (entry === undefined) {
    return registry?.get(id) ?? `legacy:block_${id}`;
  }
  if (typeof entry === "string") return `minecraft:${entry}`;
  if (typeof entry === "function") return `minecraft:${entry(data)}`;
  return `minecraft:${entry[data & 15] ?? entry[data & 7] ?? entry[0]}`;
}

